let currentLanguage = 'en';
const originalTextNodes = new WeakMap();
const originalAttributes = new WeakMap();
const languageCodes = { en: 'en', my: 'my', zh: 'zh-Hans' };

function t(english) {
  const entry = translations[english];
  return !entry || currentLanguage === 'en' ? english : entry[currentLanguage === 'my' ? 0 : 1];
}

function localizePage() {
  document.documentElement.lang = languageCodes[currentLanguage];
  document.title = t('Anisakan | A Highland Sanctuary');
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (!node.parentElement || /^(SCRIPT|STYLE|OPTION)$/.test(node.parentElement.tagName)) continue;
    if (!originalTextNodes.has(node)) originalTextNodes.set(node, node.nodeValue);
    const original = originalTextNodes.get(node);
    const key = original.trim();
    if (Object.prototype.hasOwnProperty.call(translations, key)) {
      const leading = original.match(/^\s*/)[0];
      const trailing = original.match(/\s*$/)[0];
      node.nodeValue = leading + t(key) + trailing;
    }
  }
  document.querySelectorAll('[aria-label], [alt], [placeholder]').forEach(element => {
    ['aria-label', 'alt', 'placeholder'].forEach(attribute => {
      if (!element.hasAttribute(attribute)) return;
      if ((element.id === 'zone-image' && attribute === 'alt') || (element.id === 'contact-message' && attribute === 'placeholder') || (element.id === 'menu-toggle' && attribute === 'aria-label')) return;
      let originals = originalAttributes.get(element);
      if (!originals) { originals = {}; originalAttributes.set(element, originals); }
      if (!(attribute in originals)) originals[attribute] = element.getAttribute(attribute);
      element.setAttribute(attribute, t(originals[attribute]));
    });
  });
}

function setLanguage(language) {
  currentLanguage = Object.prototype.hasOwnProperty.call(languageCodes, language) ? language : 'en';
  document.getElementById('language-select').value = currentLanguage;
  localizePage();
  if (typeof refreshLocalizedInteractiveContent === 'function') refreshLocalizedInteractiveContent();
}

document.addEventListener('DOMContentLoaded', () => {
  document.getElementById('language-select').addEventListener('change', event => setLanguage(event.target.value));
  setLanguage('en');
});
